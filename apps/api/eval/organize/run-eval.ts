/**
 * Smart-organization evaluation (Phase 5), free: local embedding model, no API key.
 * Loads the Phase 3 dataset (40 notes, with tags) plus topic folders, 8 near-duplicate copies
 * and 3 long notes (extra.json) into a throwaway database, then measures:
 *   - tag suggestions (leave-one-out: hide a note's tags and folder, suggest them back)
 *   - folder suggestions (same)
 *   - related notes (do they share the note's topic folder?)
 *   - duplicate detection (the 8 known copies vs false alarms)
 *   - key points (key facts of the long notes covered)
 * with threshold sweeps, and writes docs/eval/phase5.md.
 *
 *   npm run eval:organize -w apps/api
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MongoMemoryServer } from 'mongodb-memory-server';

type Item = { id: string; type: string; title: string; content: string; tags: string[] };
type Extra = {
  folders: Record<string, string[]>;
  denseTopics: { folder: string; tags: string[]; notes: { title: string; content: string }[] }[];
  nearDuplicates: { of: string; title: string; content: string }[];
  longNotes: { title: string; content: string; facts: string[][] }[];
};

const here = path.dirname(fileURLToPath(import.meta.url));
const dataset: Item[] = JSON.parse(readFileSync(path.join(here, '../search/dataset.json'), 'utf8'));
const extra: Extra = JSON.parse(readFileSync(path.join(here, 'extra.json'), 'utf8'));
const outFile = path.resolve(here, '../../../../docs/eval/phase5.md');

const TAG_NEIGHBOUR_MINS = [0.3, 0.35, 0.4, 0.45, 0.5, 0.55];
const DUPLICATE_MINS = [0.8, 0.85, 0.88, 0.9, 0.92, 0.95];
const RELATED_MINS = [0.3, 0.35, 0.4, 0.45, 0.5, 0.55];
const KEYPOINT_DIVERSITY = [1, 0.8, 0.7, 0.6, 0.5, 0.4];

const folderOf = (tags: string[]) => Object.entries(extra.folders).find(([, ts]) => tags.some((t) => ts.includes(t)))?.[0] ?? null;

async function main() {
  const mongo = await MongoMemoryServer.create();
  Object.assign(process.env, {
    NODE_ENV: 'test',
    MONGODB_URI: mongo.getUri('mindmesh_eval_organize'),
    FIREBASE_PROJECT_ID: 'demo-eval',
    FIREBASE_AUTH_EMULATOR_HOST: '127.0.0.1:9',
    VECTOR_BACKEND: 'memory',
    EMBEDDING_PROVIDER: process.env.EMBEDDING_PROVIDER ?? 'local',
    AI_DAILY_TOKEN_BUDGET: '100000000',
  });
  const mongoose = (await import('mongoose')).default;
  const { connectDb } = await import('../../src/config/db.js');
  const { createNote } = await import('../../src/modules/notes/notes.service.js');
  const { createFolder } = await import('../../src/modules/folders/folders.service.js');
  const { drain } = await import('../../src/modules/ai-processing/pipeline.js');
  const organize = await import('../../src/modules/organize/organize.service.js');
  const { Note } = await import('../../src/models/Note.js');
  const { embeddingProvider } = await import('../../src/platform/ai-client.js');
  await connectDb();

  const userId = new mongoose.Types.ObjectId().toString();
  const folderIds: Record<string, string> = {};
  for (const name of Object.keys(extra.folders)) folderIds[name] = String((await createFolder(userId, { name, color: null }))._id);

  const make = (title: string, content: string, tags: string[], folder: string | null, type = 'note') =>
    createNote(userId, { type: type as never, title, content, tags, folderId: folder ? folderIds[folder] : null, sourceUrl: null, metadata: {}, pinned: false, archived: false });

  // Dataset id <-> note id; folders by topic.
  const idOf = new Map<string, string>();
  const datasetIdOf = new Map<string, string>();
  for (const it of dataset) {
    const n = await make(it.title, it.content, it.tags, folderOf(it.tags), it.type);
    idOf.set(it.id, String(n._id));
    datasetIdOf.set(String(n._id), it.id);
  }
  const longIds: string[] = [];
  for (const l of extra.longNotes) longIds.push(String((await make(l.title, l.content, [], 'Work', 'document'))._id));
  await drain();
  const tagCount = new Map<string, number>();
  for (const it of dataset) for (const t of it.tags) tagCount.set(t, (tagCount.get(t) ?? 0) + 1);

  const pct = (x: number) => `${Math.round(x * 100)}%`;
  const lines: string[] = ['# Phase 5 smart-organization evaluation', ''];
  lines.push(`Generated by \`npm run eval:organize -w apps/api\` on ${new Date().toISOString().slice(0, 10)}. Free: local model \`${embeddingProvider().model}\`, no API key.`, '');
  lines.push(`- ${dataset.length} notes from the Phase 3 dataset with their tags, filed into topic folders (${Object.keys(extra.folders).join(', ')}) by tag; ${extra.nearDuplicates.length} near-duplicate copies; ${extra.longNotes.length} long notes for key points.`);
  lines.push('- Suggestions are leave-one-out: each note is treated as a fresh draft (its own tags and folder hidden, itself excluded) and scored against the rest.', '');

  // --- Tag and folder suggestions (leave-one-out) ---------------------------------------------
  const runSuggest = async () => {
    const rows = [];
    for (const it of dataset) {
      const s = await organize.suggestForDraft(userId, { title: it.title, content: it.content, tags: [], folderId: null, noteId: idOf.get(it.id) });
      const learnable = it.tags.some((t) => (tagCount.get(t) ?? 0) >= 2); // another note shares a tag
      const suggested = s.tags.map((t) => t.tag);
      const correct = suggested.filter((t) => it.tags.includes(t)).length;
      rows.push({ it, learnable, suggested, correct, folder: s.folder?.name ?? null, trueFolder: folderOf(it.tags) });
    }
    return rows;
  };
  const tagMetrics = (rows: Awaited<ReturnType<typeof runSuggest>>) => {
    const learn = rows.filter((r) => r.learnable);
    const unique = rows.filter((r) => !r.learnable);
    const allSuggested = rows.reduce((n, r) => n + r.suggested.length, 0);
    return {
      hit: learn.filter((r) => r.correct > 0).length / (learn.length || 1),
      precision: allSuggested ? rows.reduce((n, r) => n + r.correct, 0) / allSuggested : 1,
      uniqueQuiet: unique.filter((r) => !r.suggested.length).length / (unique.length || 1),
      learn: learn.length,
      unique: unique.length,
    };
  };
  const folderMetrics = (rows: Awaited<ReturnType<typeof runSuggest>>) => {
    const made = rows.filter((r) => r.folder);
    return { coverage: made.length / rows.length, accuracy: made.length ? made.filter((r) => r.folder === r.trueFolder).length / made.length : 1 };
  };

  const chosen = { ...organize.organizeSettings };
  const tagSweep = [];
  for (const votes of [1, 2]) {
    for (const v of TAG_NEIGHBOUR_MINS) {
      Object.assign(organize.organizeSettings, chosen, { tagNeighbourMin: v, tagMinVotes: votes });
      const rows = await runSuggest();
      tagSweep.push({ v, votes, ...tagMetrics(rows), folder: folderMetrics(rows) });
    }
  }
  Object.assign(organize.organizeSettings, chosen);
  const suggestRows = await runSuggest();
  const tm = tagMetrics(suggestRows);
  const fm = folderMetrics(suggestRows);

  lines.push('## Tag suggestions', '');
  lines.push(`${tm.learn} notes share a tag with at least one other note (a correct suggestion is possible); ${tm.unique} have only one-off tags (the right behaviour is to suggest nothing).`, '');
  lines.push('| Metric | Result |', '|---|---|');
  lines.push(`| Hit rate: at least one correct tag among the suggestions (shared-tag notes) | ${pct(tm.hit)} |`);
  lines.push(`| Precision: suggested tags that are correct | ${pct(tm.precision)} |`);
  lines.push(`| Quiet on one-off notes: no suggestion when none is possible | ${pct(tm.uniqueQuiet)} |`);
  lines.push('', '### Sweep: neighbours needed, and their minimum similarity', '');
  lines.push('A tag (or folder) is suggested when this many neighbours at least this similar use it.', '');
  lines.push('| Neighbours needed | Min similarity | Hit rate | Precision | Quiet on one-off notes | Folder coverage | Folder accuracy |', '|---|---|---|---|---|---|---|');
  for (const s of tagSweep) {
    const mark = s.v === chosen.tagNeighbourMin && s.votes === chosen.tagMinVotes ? ' **(chosen)**' : '';
    lines.push(`| ${s.votes} | ${s.v.toFixed(2)}${mark} | ${pct(s.hit)} | ${pct(s.precision)} | ${pct(s.uniqueQuiet)} | ${pct(s.folder.coverage)} | ${pct(s.folder.accuracy)} |`);
  }

  // A second, denser set (a separate user): 4 topics × 4 notes, consistently tagged and filed,
  // like a library that has grown several notes per topic.
  const denseUser = new mongoose.Types.ObjectId().toString();
  const denseFolderIds: Record<string, string> = {};
  const denseNotes: { id: string; tags: string[]; folder: string; title: string; content: string }[] = [];
  for (const t of extra.denseTopics) {
    denseFolderIds[t.folder] = String((await createFolder(denseUser, { name: t.folder, color: null }))._id);
    for (const n of t.notes) {
      const created = await createNote(denseUser, { type: 'note', title: n.title, content: n.content, tags: t.tags, folderId: denseFolderIds[t.folder], sourceUrl: null, metadata: {}, pinned: false, archived: false });
      denseNotes.push({ id: String(created._id), tags: t.tags, folder: t.folder, title: n.title, content: n.content });
    }
  }
  await drain();
  const runDense = async () => {
    let hit = 0, suggested = 0, correct = 0, folderMade = 0, folderRight = 0;
    for (const n of denseNotes) {
      const s = await organize.suggestForDraft(denseUser, { title: n.title, content: n.content, tags: [], folderId: null, noteId: n.id });
      const tags = s.tags.map((t) => t.tag);
      suggested += tags.length;
      correct += tags.filter((t) => n.tags.includes(t)).length;
      if (tags.some((t) => n.tags.includes(t))) hit++;
      if (s.folder) {
        folderMade++;
        if (s.folder.name === n.folder) folderRight++;
      }
    }
    return { hit: hit / denseNotes.length, precision: suggested ? correct / suggested : 1, folderCoverage: folderMade / denseNotes.length, folderAccuracy: folderMade ? folderRight / folderMade : 1 };
  };
  const denseSweep = [];
  for (const v of TAG_NEIGHBOUR_MINS) {
    Object.assign(organize.organizeSettings, chosen, { tagNeighbourMin: v });
    denseSweep.push({ v, ...(await runDense()) });
  }
  Object.assign(organize.organizeSettings, chosen);
  const dense = await runDense();
  lines.push('', '### On a denser library', '');
  lines.push(`The main set has one note per topic, so there is little for suggestions to learn from. This second set has ${extra.denseTopics.length} topics with ${extra.denseTopics[0].notes.length} notes each, consistently tagged and filed (leave-one-out as above).`, '');
  lines.push('| Metric | Result |', '|---|---|');
  lines.push(`| Tag hit rate | ${pct(dense.hit)} |`);
  lines.push(`| Tag precision | ${pct(dense.precision)} |`);
  lines.push(`| Folder coverage | ${pct(dense.folderCoverage)} |`);
  lines.push(`| Folder accuracy | ${pct(dense.folderAccuracy)} |`);
  lines.push('', '| Min similarity | Tag hit rate | Tag precision | Folder coverage | Folder accuracy |', '|---|---|---|---|---|');
  for (const s of denseSweep) lines.push(`| ${s.v.toFixed(2)}${s.v === chosen.tagNeighbourMin ? ' **(chosen)**' : ''} | ${pct(s.hit)} | ${pct(s.precision)} | ${pct(s.folderCoverage)} | ${pct(s.folderAccuracy)} |`);

  lines.push('', '## Folder suggestions', '');
  lines.push('| Metric | Result |', '|---|---|');
  lines.push(`| Coverage: notes that got a folder suggestion | ${pct(fm.coverage)} |`);
  lines.push(`| Accuracy: suggestions that name the right folder | ${pct(fm.accuracy)} |`);

  // --- Related notes ------------------------------------------------------------------------
  const runRelated = async () => {
    let shown = 0, sameFolder = 0, withAny = 0;
    for (const it of dataset) {
      const r = await organize.relatedNotes(userId, idOf.get(it.id)!);
      const top = r.items.slice(0, 3);
      if (top.length) withAny++;
      for (const x of top) {
        shown++;
        const other = dataset.find((d) => d.id === datasetIdOf.get(x.note._id));
        if (other && folderOf(other.tags) === folderOf(it.tags)) sameFolder++;
      }
    }
    return { precision: shown ? sameFolder / shown : 1, coverage: withAny / dataset.length, avg: shown / dataset.length };
  };
  const relatedSweep = [];
  for (const v of RELATED_MINS) {
    Object.assign(organize.organizeSettings, chosen, { relatedMin: v });
    relatedSweep.push({ v, ...(await runRelated()) });
  }
  Object.assign(organize.organizeSettings, chosen);
  const rel = await runRelated();
  lines.push('', '## Related notes', '');
  lines.push('Proxy for "on the same topic": the related note is in the same topic folder.', '');
  lines.push('| Metric | Result |', '|---|---|');
  lines.push(`| Same-topic share of the top 3 related notes | ${pct(rel.precision)} |`);
  lines.push(`| Notes with at least one related note | ${pct(rel.coverage)} |`);
  lines.push(`| Related notes shown per note (top 3) | ${rel.avg.toFixed(1)} |`);
  lines.push('', '### Sweep: minimum similarity for a related note', '');
  lines.push('| Value | Same-topic share | Notes with any | Shown per note |', '|---|---|---|---|');
  for (const s of relatedSweep) lines.push(`| ${s.v.toFixed(2)}${s.v === chosen.relatedMin ? ' **(chosen)**' : ''} | ${pct(s.precision)} | ${pct(s.coverage)} | ${s.avg.toFixed(1)} |`);

  // --- Duplicates ---------------------------------------------------------------------------
  // Before saving: does the editor warn about the original?
  const warnedBeforeSave: boolean[] = [];
  for (const d of extra.nearDuplicates) {
    const s = await organize.suggestForDraft(userId, { title: d.title, content: d.content, tags: [], folderId: null });
    warnedBeforeSave.push(s.duplicates.some((x) => x._id === idOf.get(d.of)));
  }
  // After saving: the duplicates view.
  const copyIds: string[] = [];
  for (const d of extra.nearDuplicates) copyIds.push(String((await make(d.title, d.content, [], null))._id));
  await drain();
  const expectedPairs = new Set(extra.nearDuplicates.map((d, i) => [idOf.get(d.of)!, copyIds[i]].sort().join(':')));
  const dupSweep = [];
  for (const v of DUPLICATE_MINS) {
    Object.assign(organize.organizeSettings, chosen, { duplicateMin: v });
    const { pairs } = await organize.duplicatePairs(userId);
    const keys = pairs.map((p) => [p.a._id, p.b._id].sort().join(':'));
    const found = keys.filter((k) => expectedPairs.has(k)).length;
    dupSweep.push({ v, recall: found / expectedPairs.size, falseAlarms: keys.length - found });
  }
  Object.assign(organize.organizeSettings, chosen);
  const chosenDup = dupSweep.find((s) => s.v === chosen.duplicateMin);
  const falseAlarms = (await organize.duplicatePairs(userId)).pairs.filter((p) => !expectedPairs.has([p.a._id, p.b._id].sort().join(':')));
  lines.push('', '## Duplicate detection', '');
  lines.push(`${extra.nearDuplicates.length} lightly reworded copies of existing notes; every other pair counts as a false alarm.`, '');
  lines.push('| Metric | Result |', '|---|---|');
  lines.push(`| Warned while writing the copy (before saving) | ${pct(warnedBeforeSave.filter(Boolean).length / warnedBeforeSave.length)} |`);
  if (chosenDup) {
    lines.push(`| Copies found in "Possible duplicates" | ${pct(chosenDup.recall)} |`);
    lines.push(`| False alarms (pairs that aren't copies) | ${chosenDup.falseAlarms} |`);
  }
  lines.push('', '### Sweep: minimum similarity for a duplicate', '');
  lines.push('| Value | Copies found | False alarms |', '|---|---|---|');
  for (const s of dupSweep) lines.push(`| ${s.v.toFixed(2)}${s.v === chosen.duplicateMin ? ' **(chosen)**' : ''} | ${pct(s.recall)} | ${s.falseAlarms} |`);
  if (falseAlarms.length) {
    lines.push('', 'False alarms at the chosen value:', '');
    for (const p of falseAlarms) lines.push(`- *${p.a.title}* and *${p.b.title}* (${Math.round(p.score * 100)}%)`);
  }

  // --- Key points ---------------------------------------------------------------------------
  lines.push('', '## Key points', '');
  lines.push('| Note | Key points | Facts covered |', '|---|---|---|');
  let factsHit = 0, factsAll = 0;
  for (let i = 0; i < extra.longNotes.length; i++) {
    const n = await Note.findById(longIds[i]).lean();
    const text = (n?.keyPoints ?? []).join(' ').toLowerCase();
    const facts = extra.longNotes[i].facts;
    const hit = facts.filter((alts) => alts.some((a) => text.includes(a.toLowerCase()))).length;
    factsHit += hit;
    factsAll += facts.length;
    lines.push(`| ${extra.longNotes[i].title} | ${(n?.keyPoints ?? []).map((p) => p.replace(/\|/g, '\\|')).join(' · ') || '—'} | ${hit} / ${facts.length} |`);
  }
  const shortWithPoints = await Note.countDocuments({ _id: { $in: [...idOf.values()] }, 'keyPoints.0': { $exists: true } });
  lines.push('', `Key facts covered: **${pct(factsHit / factsAll)}**. Short dataset notes given key points: ${shortWithPoints} of ${dataset.length} (they're short enough to read as they are).`);

  // Sweep the relevance/diversity trade-off by re-running the key-point picker on the stored note vectors.
  const { keyPointsFor, keyPointSettings } = await import('../../src/modules/organize/key-points.js');
  const { NoteVector } = await import('../../src/models/NoteVector.js');
  const chosenKp = { ...keyPointSettings };
  lines.push('', '### Sweep: relevance vs diversity (1 = only "represents the note", lower = also "differs from points already picked")', '');
  lines.push('| Value | Facts covered |', '|---|---|');
  for (const d of KEYPOINT_DIVERSITY) {
    Object.assign(keyPointSettings, chosenKp, { diversity: d });
    let hit = 0;
    for (let i = 0; i < extra.longNotes.length; i++) {
      const v = (await NoteVector.findOne({ noteId: longIds[i] }).lean())!.embedding;
      const text = (await keyPointsFor(userId, extra.longNotes[i].content, v)).join(' ').toLowerCase();
      hit += extra.longNotes[i].facts.filter((alts) => alts.some((a) => text.includes(a.toLowerCase()))).length;
    }
    lines.push(`| ${d.toFixed(1)}${d === chosenKp.diversity ? ' **(chosen)**' : ''} | ${pct(hit / factsAll)} |`);
  }
  Object.assign(keyPointSettings, chosenKp);

  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(outFile, lines.join('\n') + '\n');
  console.log(lines.join('\n'));
  await mongoose.disconnect();
  await mongo.stop();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
